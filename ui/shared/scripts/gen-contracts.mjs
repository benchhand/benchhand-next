// Generates TypeScript types and Ajv standalone validators from the published contract schemas (ADR-0017).
// Run by tools/gen (`just contracts`), which passes the schema list, so discovery lives in one place.
//
// Usage: node gen-contracts.mjs <schemasDir> <outDir> <relative/path.schema.json>...

import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { compile } from "json-schema-to-typescript";
import { toSafeString } from "json-schema-to-typescript/dist/src/utils.js";

const [schemasDir, outDir, ...relPaths] = process.argv.slice(2);

function header(source) {
  return `// Generated by tools/gen (\`just contracts\`). Do not edit.\n// Source: ${source}\n`;
}

function stem(relPath) {
  return relPath.replace(/\.schema\.json$/, "");
}

function collectExtensionKeywords(node, found) {
  if (Array.isArray(node)) {
    node.forEach((item) => collectExtensionKeywords(item, found));
  } else if (node && typeof node === "object") {
    for (const [key, value] of Object.entries(node)) {
      if (key.startsWith("x-")) found.add(key);
      collectExtensionKeywords(value, found);
    }
  }
}

async function loadSchemas() {
  const schemas = new Map();
  for (const relPath of relPaths) {
    const text = await readFile(path.join(schemasDir, relPath), "utf8");
    schemas.set(relPath, JSON.parse(text));
  }
  return schemas;
}

function newAjv(schemas) {
  // Unknown keywords are errors; Ajv's style lints (strictTypes, strictRequired) are not contract rules.
  // Formats are annotations, as in the Python validator (benchhand_contracts.validate).
  const ajv = new Ajv2020({
    code: { source: true, esm: true },
    strictSchema: true,
    strictNumbers: true,
    strictTypes: false,
    strictTuples: false,
    strictRequired: false,
    validateFormats: false,
  });
  const keywords = new Set();
  for (const schema of schemas.values()) collectExtensionKeywords(schema, keywords);
  for (const keyword of [...keywords].sort()) ajv.addKeyword(keyword);
  for (const schema of schemas.values()) ajv.addSchema(schema);
  return ajv;
}

function validatorExports(schema) {
  const exports = { validate: schema.$id };
  for (const name of Object.keys(schema.$defs ?? {})) {
    exports[`validate${name}`] = `${schema.$id}#/$defs/${name}`;
  }
  return exports;
}

function validatorDeclarations(exports) {
  const lines = ['import type { ValidateFunction } from "ajv";', ""];
  for (const name of Object.keys(exports)) {
    lines.push(`export declare const ${name}: ValidateFunction;`);
  }
  return `${lines.join("\n")}\n`;
}

const WRAPPER = "ContractsGenWrapper";

// json-schema-to-typescript emits unreferenced $defs only under an object root, so the contract's own
// root goes into $defs beside the others, under a wrapper object that is stripped from the output.
function wrapped(relPath, schema) {
  const { $id, $schema, $defs, ...root } = schema;
  const rootName = schema.title ?? stem(relPath);
  return { title: WRAPPER, type: "object", properties: {}, additionalProperties: false, $defs: { [rootName]: root, ...$defs } };
}

function stripWrapper(code) {
  const out = [];
  const lines = code.split("\n");
  for (let i = 0; i < lines.length; i += 1) {
    const line = lines[i];
    if (line === `export interface ${WRAPPER} {}`) continue;
    if (line.includes(`referenced by \`${WRAPPER}\`'s JSON-Schema`)) {
      i += 1; // the "via the `definition`" line that follows
      if (out.at(-1)?.trim() === "*") out.pop();
      if (out.at(-1)?.trim() === "/**" && lines[i + 1]?.trim() === "*/") {
        out.pop();
        i += 1;
      }
      continue;
    }
    out.push(line);
  }
  return out.join("\n");
}

// The compiler names a $def's type after its title, or else its key, made a safe identifier:
// `semantic_id` becomes `SemanticId`.
function typeName(defs, key) {
  return toSafeString(defs[key]?.title ?? key);
}

function declares(code, name) {
  return new RegExp(`^export (type|interface|enum) ${name}\\b`, "m").test(code);
}

// A $def that is only a $ref to another local $def is folded into its target by the compiler,
// so it gets an explicit alias here and every $def stays importable by its type name.
// An alias can target another alias, so they are resolved until none is left.
function refAliases(schema, code) {
  const defs = schema.$defs ?? {};
  let declared = code;
  const aliases = [];
  let pending = Object.keys(defs).filter((key) => !declares(code, typeName(defs, key)));
  while (pending.length) {
    const unresolved = [];
    for (const key of pending) {
      const target = /^#\/\$defs\/([^/]+)$/.exec(defs[key].$ref ?? "")?.[1];
      if (target && declares(declared, typeName(defs, target))) {
        const alias = `export type ${typeName(defs, key)} = ${typeName(defs, target)};`;
        aliases.push(alias);
        declared += `\n${alias}`;
      } else {
        unresolved.push(key);
      }
    }
    if (unresolved.length === pending.length) {
      const names = unresolved.map((key) => `${key} (${typeName(defs, key)})`).join(", ");
      throw new Error(`${schema.$id}: no TypeScript type for $defs ${names}`);
    }
    pending = unresolved;
  }
  return aliases.length ? `${aliases.join("\n")}\n` : "";
}

async function typesFor(relPath, schema) {
  // Refs resolve from the file's own directory, never from the $id host.
  const code = await compile(wrapped(relPath, schema), WRAPPER, {
    bannerComment: "",
    cwd: path.dirname(path.join(schemasDir, relPath)),
    declareExternallyReferenced: true,
    unreachableDefinitions: true,
    additionalProperties: true,
    format: true,
  });
  const types = stripWrapper(code);
  return types + refAliases(schema, types);
}

// Ajv's ESM output still calls require() for its runtime helpers, which ESM modules don't have.
// Each helper becomes an import of the CommonJS module, whose default export is module.exports.
function esmRuntimeImports(code) {
  const helpers = new Set();
  const body = code.replace(/require\("ajv\/dist\/runtime\/([a-z0-9]+)"\)/g, (_match, helper) => {
    helpers.add(helper);
    return `ajvRuntime_${helper}`;
  });
  const imports = [...helpers].sort().map((helper) => `import ajvRuntime_${helper} from "ajv/dist/runtime/${helper}.js";\n`);
  return imports.join("") + body;
}

async function writeOutputs(ajv, relPath, schema) {
  const source = `contracts/${stem(relPath)}.tsp`;
  const base = path.join(outDir, stem(relPath));
  await mkdir(path.dirname(base), { recursive: true });
  const exports = validatorExports(schema);
  await writeFile(`${base}.ts`, header(source) + "\n" + (await typesFor(relPath, schema)));
  await writeFile(`${base}.validate.js`, header(source) + esmRuntimeImports(standaloneCode(ajv, exports)) + "\n");
  await writeFile(`${base}.validate.d.ts`, header(source) + "\n" + validatorDeclarations(exports));
}

const schemas = await loadSchemas();
const ajv = newAjv(schemas);
for (const [relPath, schema] of schemas) {
  await writeOutputs(ajv, relPath, schema);
}
