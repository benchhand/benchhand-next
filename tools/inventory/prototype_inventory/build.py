"""The inventory: the prototype's Python files scanned, each joined to its entry in the reference map."""

from __future__ import annotations

import json
from pathlib import Path
from typing import TypedDict

from reference_map.coverage import reference_files, required_files
from reference_map.entries import Entry, ReferenceMap, pattern_regex
from reference_map.render import AREA_TITLES

from .commands import CommandRecord
from .scan import ClassRecord, FunctionRecord, scan_source

SCHEMA_VERSION = 1
GENERATED_NOTICE = (
    "Generated by tools/inventory (`just inventory --write`) from the prototype and reference-map.yaml. "
    "Do not edit."
)


class InventoryError(Exception):
    """The inventory can't be built or checked; the message lists every problem."""

    def __init__(self, problems: list[str]) -> None:
        super().__init__("\n".join(problems))
        self.problems = problems


class MapJoin(TypedDict):
    map_entry: str
    """The ``path`` of the reference-map entry the file matched."""
    home: list[str]
    phase: int | None
    status: str
    reason: str
    note: str
    inferred: bool


class FileRecord(MapJoin):
    path: str
    area: str
    summary: str
    entry_points: list[str]
    commands: list[CommandRecord]
    classes: list[ClassRecord]
    functions: list[FunctionRecord]
    """The file's functions and methods inherit its map entry: the map has no finer entries."""


class Counts(TypedDict):
    files: int
    commands: int
    """The command lines that can be run: a parser or click command with no subcommand under it."""
    classes: int
    functions: int
    methods: int


class Summary(Counts):
    by_area: dict[str, Counts]


class Inventory(TypedDict):
    schema_version: int
    generated: str
    reference_commit: str
    summary: Summary
    files: list[FileRecord]


def area_order(area: str) -> tuple[bool, str]:
    """Skills by name, then ``agents-and-harness`` and ``examples``, as the function map orders them."""
    return (area in AREA_TITLES, area)


def inventory_files(reference_dir: Path) -> list[str]:
    """The Python files that the reference map requires an entry for, sorted."""
    files = required_files(reference_files([reference_dir]))
    return [path for path in files if path.endswith(".py")]


def find_entry(path: str, reference: ReferenceMap) -> Entry:
    hits = [entry for entry in reference.entries if pattern_regex(entry.path).match(path)]
    if len(hits) != 1:
        raise InventoryError([f"{path}: matched by {len(hits)} reference-map entries; expected one"])
    return hits[0]


def join_entry(entry: Entry) -> MapJoin:
    return {
        "map_entry": entry.path,
        "home": list(entry.homes),
        "phase": entry.phase,
        "status": entry.status,
        "reason": entry.reason,
        "note": entry.note,
        "inferred": entry.inferred,
    }


def build_inventory(reference_dir: Path, reference: ReferenceMap) -> Inventory:
    files: list[FileRecord] = []
    problems: list[str] = []
    for path in inventory_files(reference_dir):
        entry = find_entry(path, reference)
        try:
            scanned = scan_source((reference_dir / path).read_text(encoding="utf-8"), path)
        except SyntaxError as error:
            problems.append(f"{path}: {error}")
            continue
        files.append({"path": path, "area": entry.area, **join_entry(entry), **scanned})
    if problems:
        raise InventoryError(problems)
    return {
        "schema_version": SCHEMA_VERSION,
        "generated": GENERATED_NOTICE,
        "reference_commit": reference.reference_commit,
        "summary": summarise(files),
        "files": files,
    }


def count_commands(commands: list[CommandRecord]) -> int:
    """The parsers and commands with no subcommand below them."""
    paths = [command["command"] for command in commands]
    return sum(
        not any(other.startswith(f"{path} " if path else "") and other != path for other in paths)
        for path in paths
    )


def _counts(files: list[FileRecord]) -> Counts:
    functions = [function for file in files for function in file["functions"]]
    return {
        "files": len(files),
        "commands": sum(count_commands(file["commands"]) for file in files),
        "classes": sum(len(file["classes"]) for file in files),
        "functions": sum(function["kind"].endswith("function") for function in functions),
        "methods": sum(function["kind"].endswith("method") for function in functions),
    }


def summarise(files: list[FileRecord]) -> Summary:
    areas = sorted({file["area"] for file in files}, key=area_order)
    return {
        **_counts(files),
        "by_area": {area: _counts([file for file in files if file["area"] == area]) for area in areas},
    }


def check_joined(data: Inventory, reference: ReferenceMap) -> list[str]:
    """What in the committed inventory no longer agrees with the reference map: a file with no entry, or
    an entry whose home, phase or status changed. Needs no copy of the prototype."""
    problems: list[str] = []
    if data["reference_commit"] != reference.reference_commit:
        problems.append(
            f"reference_commit {data['reference_commit']} is not the map's {reference.reference_commit}"
        )
    for file in data["files"]:
        try:
            entry = find_entry(file["path"], reference)
        except InventoryError as error:
            problems += error.problems
            continue
        joined = join_entry(entry)
        if {key: file[key] for key in joined} != joined or file["area"] != entry.area:  # type: ignore[literal-required]
            problems.append(f"{file['path']}: its reference-map entry {entry.path} changed")
    return problems


def dump_json(data: Inventory) -> str:
    return json.dumps(data, indent=1, ensure_ascii=False) + "\n"
