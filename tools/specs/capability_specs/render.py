"""docs/specs/phase-2.md: every Phase 2 capability with its spec, the block graph, a suggested block order,
the questions that hold blocks, and the Phase 2 register entries no spec closes."""

from __future__ import annotations

import re
from collections import Counter
from typing import Any

from .checks import CAPABILITY, QUESTION, block_dependencies
from .specs import CATALOGUE_FILE, PHASE, REGISTER_FILE, Index, Sources, Spec

CATALOGUE_PAGE = "../architecture/capabilities.md"
SIZES = ("S", "M", "L")


def render_page(index: Index, specs: list[Spec], sources: Sources) -> str:
    sections = [
        _header(),
        _capabilities(specs, sources),
        _specs(specs),
        _graph(specs),
        _order(specs, sources),
        _questions(specs, sources),
        _open_issues(specs, sources),
    ]
    return "\n\n".join(sections) + "\n"


def _header() -> str:
    return (
        f"# Phase {PHASE} specs\n\n"
        f"Generated by `tools/specs` (`just specs --write`) from the specs' front matter, `{CATALOGUE_FILE}` "
        f"and `{REGISTER_FILE}`. Don't edit it: change a spec and regenerate. The spec format is in "
        "[README.md](README.md)."
    )


def _capabilities(specs: list[Spec], sources: Sources) -> str:
    covered = {capability: spec for spec in specs for capability in spec.capabilities}
    rows = [
        "| Capability | Title | Catalogue status | Spec |",
        "|---|---|---|---|",
    ]
    for capability in sources.phase_capabilities():
        item = sources.capabilities[capability]
        spec = covered.get(capability)
        cell = f"[{spec.id}]({spec.id}.md)" if spec else "not yet specced"
        rows.append(
            f"| [{capability}]({CATALOGUE_PAGE}#{capability}) | {item['title']} | {item['status']} | {cell} |"
        )
    others = [capability for capability in covered if capability not in sources.phase_capabilities()]
    text = (
        f"## Capabilities\n\nEvery Phase {PHASE} capability of the catalogue, in catalogue order.\n\n"
        + "\n".join(rows)
    )
    if others:
        names = ", ".join(f"`{capability}` ({covered[capability].id})" for capability in others)
        text += f"\n\nThe specs also cover capabilities of other phases: {names}."
    return text


def _specs(specs: list[Spec]) -> str:
    rows = ["| Spec | Title | Status | Capabilities | Blocks | Sizes |", "|---|---|---|---|---|---|"]
    for spec in specs:
        sizes = Counter(block["size"] for block in spec.blocks)
        size_cell = ", ".join(f"{sizes[size]} {size}" for size in SIZES if sizes[size])
        capabilities = ", ".join(f"`{capability}`" for capability in spec.capabilities)
        rows.append(
            f"| [{spec.id}]({spec.id}.md) | {spec.front['title']} | {spec.front['status']} | {capabilities} "
            f"| {len(spec.blocks)} | {size_cell} |"
        )
    return "## Specs\n\n" + "\n".join(rows)


def _node(target: str) -> str:
    return re.sub(r"[^A-Za-z0-9]", "_", target)


def _label(text: str) -> str:
    return text.replace('"', "#quot;")


def _graph(specs: list[Spec]) -> str:
    lines = ["flowchart TD"]
    outside: list[str] = []
    edges: list[str] = []
    for spec in specs:
        lines.append(f'  subgraph {_node("spec " + spec.id)}["{spec.id}"]')
        for block in spec.blocks:
            lines.append(
                f'    {_node(block["id"])}["{block["id"]} ({block["size"]}): {_label(block["title"])}"]'
            )
            for target in block["depends_on"]:
                if target.startswith((QUESTION, CAPABILITY)) and target not in outside:
                    outside.append(target)
                edges.append(f"  {_node(target)} --> {_node(block['id'])}")
        lines.append("  end")
    for target in outside:
        shape = '{{"%s"}}' if target.startswith(QUESTION) else '(["%s"])'
        lines.append(f"  {_node(target)}" + shape % target.replace(":", ": "))
    text = (
        "## Block graph\n\nAn arrow runs from what a block needs to the block. A hexagon is an open question in "
        "the catalogue, and a rounded box a capability that no spec covers yet.\n\n"
    )
    return text + "```mermaid\n" + "\n".join(lines + edges) + "\n```"


def suggested_order(specs: list[Spec]) -> list[dict[str, Any]]:
    """The blocks in dependency order; among the blocks that are ready, the index's spec order, then the block's."""
    rank = {
        block["id"]: (position, number)
        for position, spec in enumerate(specs)
        for number, block in enumerate(spec.blocks)
    }
    blocks = {block["id"]: block for spec in specs for block in spec.blocks}
    waiting = {key: set(block_dependencies(block)) for key, block in blocks.items()}
    order: list[dict[str, Any]] = []
    while waiting:
        ready = sorted((key for key, needs in waiting.items() if not needs), key=rank.__getitem__)
        if not ready:
            break
        order.append(blocks[ready[0]])
        del waiting[ready[0]]
        for needs in waiting.values():
            needs.discard(ready[0])
    return order


def _order(specs: list[Spec], sources: Sources) -> str:
    spec_of = {block["id"]: spec.id for spec in specs for block in spec.blocks}
    lines: list[str] = []
    for number, block in enumerate(suggested_order(specs), start=1):
        after = block_dependencies(block)
        waits = [target for target in block["depends_on"] if target.startswith((QUESTION, CAPABILITY))]
        line = f"{number}. **{block['id']}** ({block['size']}, {spec_of[block['id']]}): {block['title']}."
        if after:
            line += " After " + ", ".join(after) + "."
        if waits:
            line += " Waits on " + ", ".join(_wait(target, sources) for target in waits) + "."
        lines.append(line)
    return (
        "## Suggested order\n\n"
        "The blocks in dependency order. Among the blocks that are ready, the order of the specs in the "
        "README comes first, then each spec's own order. A block that waits on an open question or an "
        "unspecced capability keeps its place, and it starts once that is settled.\n\n" + "\n".join(lines)
    )


def _wait(target: str, sources: Sources) -> str:
    if target.startswith(QUESTION):
        question = target.removeprefix(QUESTION)
        kind = "blocking" if sources.questions.get(question, {}).get("blocking") else "non-blocking"
        return f"`{question}` ({kind})"
    return f"capability `{target.removeprefix(CAPABILITY)}`"


def _questions(specs: list[Spec], sources: Sources) -> str:
    held: dict[str, list[str]] = {}
    for spec in specs:
        for block in spec.blocks:
            for target in block["depends_on"]:
                if target.startswith(QUESTION):
                    held.setdefault(target.removeprefix(QUESTION), []).append(block["id"])
    rows = ["| Question | Blocking | Owner | Blocks it holds |", "|---|---|---|---|"]
    for question, blocks in held.items():
        item = sources.questions[question]
        rows.append(
            f"| [{question}]({CATALOGUE_PAGE}#{question}) | {'yes' if item['blocking'] else 'no'} "
            f"| {item.get('owner', 'none')} | {', '.join(blocks)} |"
        )
    return "## Open questions that hold blocks\n\n" + "\n".join(rows)


def _open_issues(specs: list[Spec], sources: Sources) -> str:
    closed = {entry["id"] for spec in specs for entry in spec.closes}
    deferred = {entry["id"]: entry["to"] for spec in specs for entry in spec.defers}
    rows = ["| Entry | Disposition | Deferred to | Title |", "|---|---|---|---|"]
    for issue in sources.phase_issues():
        if issue in closed:
            continue
        item = sources.issues[issue]
        rows.append(f"| {issue} | {item['disposition']} | {deferred.get(issue, 'none')} | {item['title']} |")
    count = len(rows) - 2
    return (
        f"## Phase {PHASE} register entries no spec closes\n\n"
        f'{count} of the {len(sources.phase_issues())} Phase {PHASE} entries of the issue register. "Deferred '
        'to" names the capability that a spec has handed the entry to.\n\n' + "\n".join(rows)
    )
