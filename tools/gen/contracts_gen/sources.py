"""Contract sources and output locations for the generator (ADR-0017)."""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any
from urllib.parse import urlsplit

REPO_ROOT = Path(__file__).resolve().parents[3]
CONTRACTS_DIR = "contracts"
SCHEMA_SUFFIX = ".schema.json"

PACKAGE_DIR = "packages/benchhand-contracts/src/benchhand_contracts"
MODELS_OUT = f"{PACKAGE_DIR}/models"
SCHEMAS_OUT = f"{PACKAGE_DIR}/schemas"
EXAMPLES_OUT = f"{PACKAGE_DIR}/examples"
TYPESCRIPT_OUT = "ui/shared/contracts"
DOCS_OUT = "docs/contract/generated"
OUTPUT_DIRS = (MODELS_OUT, SCHEMAS_OUT, EXAMPLES_OUT, TYPESCRIPT_OUT, DOCS_OUT)

GENERATED_NOTICE = "Generated by tools/gen (`just contracts`). Do not edit."


class ContractSourceError(Exception):
    """A file under contracts/ can't be used as a generator input."""


@dataclass(frozen=True)
class Contract:
    """One schema file under contracts/."""

    rel_path: str
    """Path below contracts/, with forward slashes, e.g. ``provider/protocol.schema.json``."""
    schema: dict[str, Any]

    @property
    def source(self) -> str:
        return f"{CONTRACTS_DIR}/{self.rel_path}"

    @property
    def stem(self) -> str:
        """``provider/protocol`` for ``provider/protocol.schema.json``."""
        return self.rel_path.removesuffix(SCHEMA_SUFFIX)

    @property
    def schema_id(self) -> str:
        return self.schema["$id"]


def load_contracts(contracts_dir: Path) -> list[Contract]:
    """Every ``*.schema.json`` below ``contracts_dir``, in path order."""
    contracts = []
    for path in sorted(contracts_dir.rglob(f"*{SCHEMA_SUFFIX}")):
        rel_path = path.relative_to(contracts_dir).as_posix()
        schema = json.loads(path.read_text(encoding="utf-8"))
        _check_source(rel_path, schema)
        contracts.append(Contract(rel_path, schema))
    if not contracts:
        raise ContractSourceError(f"no *{SCHEMA_SUFFIX} files under {contracts_dir}")
    return contracts


def _check_source(rel_path: str, schema: dict[str, Any]) -> None:
    if not isinstance(schema.get("$id"), str):
        raise ContractSourceError(f"{rel_path}: missing $id")
    for ref in _refs(schema):
        if urlsplit(ref).scheme:
            # The generators resolve refs from disk; an absolute URI would make them fetch it.
            raise ContractSourceError(f"{rel_path}: $ref {ref!r} must be relative to the file or a #fragment")


def _refs(node: Any) -> list[str]:
    if isinstance(node, list):
        return [ref for item in node for ref in _refs(item)]
    if not isinstance(node, dict):
        return []
    found = [node["$ref"]] if isinstance(node.get("$ref"), str) else []
    return found + [ref for key, value in node.items() if key != "$ref" for ref in _refs(value)]
