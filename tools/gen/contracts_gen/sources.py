"""Contract sources and output locations for the generator (ADR-0017)."""

from __future__ import annotations

import json
import re
from collections.abc import Callable, Iterator
from dataclasses import dataclass
from pathlib import Path
from typing import Any
from urllib.parse import urlsplit

REPO_ROOT = Path(__file__).resolve().parents[3]
CONTRACTS_DIR = "contracts"
SCHEMA_SUFFIX = ".schema.json"
TYPESPEC_SUFFIX = ".tsp"

PACKAGE_DIR = "packages/benchhand-contracts/src/benchhand_contracts"
MODELS_OUT = f"{PACKAGE_DIR}/models"
SCHEMAS_OUT = f"{PACKAGE_DIR}/schemas"
EXAMPLES_OUT = f"{PACKAGE_DIR}/examples"
TYPESCRIPT_OUT = "ui/shared/contracts"
DOCS_OUT = "docs/contract/generated"
OUTPUT_DIRS = (MODELS_OUT, SCHEMAS_OUT, EXAMPLES_OUT, TYPESCRIPT_OUT, DOCS_OUT)

GENERATED_NOTICE = "Generated by tools/gen (`just contracts`). Do not edit."
CEL_CONTRACT = "common/cel.schema.json"
"""The one CEL expression type. The flow interpreter finds every expression by a ``$ref`` to it."""
_MENTIONS_CEL = re.compile(r"\bCEL\b")
# Keywords whose value maps names to schemas, so a key there such as "examples" is a property name.
_SCHEMA_MAPS = frozenset({"properties", "patternProperties", "$defs", "dependentSchemas"})
# Keywords whose value is instance data, not a schema.
_DATA_KEYWORDS = frozenset({"examples", "default", "const", "enum"})


class ContractSourceError(Exception):
    """A published schema can't be used as a generator input."""


@dataclass(frozen=True)
class Contract:
    """One published schema, generated from contracts/ into the package's schemas/ directory."""

    rel_path: str
    """Path below schemas/, with forward slashes, e.g. ``provider/protocol.schema.json``."""
    schema: dict[str, Any]

    @property
    def source(self) -> str:
        """The TypeSpec file the schema comes from, e.g. ``contracts/provider/protocol.tsp``."""
        return f"{CONTRACTS_DIR}/{self.stem}{TYPESPEC_SUFFIX}"

    @property
    def stem(self) -> str:
        """``provider/protocol`` for ``provider/protocol.schema.json``."""
        return self.rel_path.removesuffix(SCHEMA_SUFFIX)

    @property
    def schema_id(self) -> str:
        return self.schema["$id"]


def load_contracts(schemas_dir: Path) -> list[Contract]:
    """Every ``*.schema.json`` below ``schemas_dir``, in path order."""
    contracts = []
    for path in sorted(schemas_dir.rglob(f"*{SCHEMA_SUFFIX}")):
        rel_path = path.relative_to(schemas_dir).as_posix()
        schema = json.loads(path.read_text(encoding="utf-8"), parse_constant=_reject_constant(rel_path))
        _check_source(rel_path, schema)
        contracts.append(Contract(rel_path, schema))
    if not contracts:
        raise ContractSourceError(f"no *{SCHEMA_SUFFIX} files under {schemas_dir}")
    return contracts


def _reject_constant(rel_path: str) -> Callable[[str], Any]:
    def reject(constant: str) -> Any:
        raise ContractSourceError(f"{rel_path}: {constant} is not valid JSON")

    return reject


def _check_source(rel_path: str, schema: dict[str, Any]) -> None:
    if not isinstance(schema.get("$id"), str):
        raise ContractSourceError(f"{rel_path}: missing $id")
    for ref in _refs(schema):
        if urlsplit(ref).scheme:
            # The generators resolve refs from disk; an absolute URI would make them fetch it.
            raise ContractSourceError(f"{rel_path}: $ref {ref!r} must be relative to the file or a #fragment")
    if rel_path != CEL_CONTRACT:
        for pointer in _plain_cel_strings(schema, ""):
            raise ContractSourceError(
                f"{rel_path}#{pointer}: a CEL expression is a plain string; $ref {CEL_CONTRACT}#/$defs/CelExpression instead"
            )


def _refs(node: Any) -> list[str]:
    if isinstance(node, list):
        return [ref for item in node for ref in _refs(item)]
    if not isinstance(node, dict):
        return []
    found = [node["$ref"]] if isinstance(node.get("$ref"), str) else []
    return found + [ref for key, value in node.items() if key != "$ref" for ref in _refs(value)]


def _plain_cel_strings(node: Any, pointer: str) -> Iterator[str]:
    """Where a schema whose description says CEL is a string, or an array of strings, of its own.

    Walks schema positions only: examples, defaults, const and enum values and x- annotations are data, so a
    payload that looks like a schema there is never linted.
    """
    if isinstance(node, list):
        for index, item in enumerate(node):
            yield from _plain_cel_strings(item, f"{pointer}/{index}")
        return
    if not isinstance(node, dict):
        return
    description = node.get("description")
    if isinstance(description, str) and _MENTIONS_CEL.search(description) and _is_plain_string(node):
        yield pointer
    for key, value in node.items():
        child = f"{pointer}/{_escape(key)}"
        if key in _SCHEMA_MAPS and isinstance(value, dict):
            for name, schema in value.items():
                yield from _plain_cel_strings(schema, f"{child}/{_escape(name)}")
        elif key not in _DATA_KEYWORDS and not key.startswith("x-"):
            yield from _plain_cel_strings(value, child)


def _escape(key: str) -> str:
    return key.replace("~", "~0").replace("/", "~1")


def _is_plain_string(node: dict[str, Any]) -> bool:
    items = node.get("items")
    return node.get("type") == "string" or (isinstance(items, dict) and items.get("type") == "string")
