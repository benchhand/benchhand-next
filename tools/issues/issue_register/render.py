"""``docs/migration/issue-register.md``: the register's counts, design rules, owner decisions and rechecks."""

from __future__ import annotations

from collections import Counter
from collections.abc import Iterable
from typing import Any

from .register import REGISTER_FILE, Register

GENERATED_NOTICE = f"Generated by tools/issues (`just issues --write`) from `{REGISTER_FILE}`. Do not edit."
DISPOSITIONS = ("port-fix", "design-input", "contract", "already-covered", "not-applicable", "decide")
BEAD_DISPOSITIONS = (*DISPOSITIONS[:-1], "duplicate")
KINDS = ("bug", "gap", "false-pass", "false-fail", "design-rule", "decision", "process")


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def _count_table(title: str, counts: Counter[str], order: Iterable[str]) -> list[str]:
    rows = [f"| {key} | {counts[key]} |" for key in order if counts[key]]
    return [f"| {title} | Count |", "|---|---|", *rows, f"| total | {sum(counts.values())} |", ""]


def _phase(issue: dict[str, Any]) -> str:
    phase = issue["benchhand_next"]["phase"]
    return "no phase" if phase is None else f"Phase {phase}"


def _area_table(register: Register) -> list[str]:
    areas = sorted({issue["area"] for issue in register.issues})
    header = ["| Area |", *(f" {name} |" for name in DISPOSITIONS), " Issues |"]
    lines = ["".join(header), "|---" * (len(DISPOSITIONS) + 2) + "|"]
    for area in areas:
        counts = Counter(issue["disposition"] for issue in register.issues if issue["area"] == area)
        cells = "".join(f" {counts[name] or ''} |" for name in DISPOSITIONS)
        lines.append(f"| {area} |{cells} {sum(counts.values())} |")
    return [*lines, ""]


def _bead_section(register: Register) -> list[str]:
    in_issues = [bead for issue in register.issues for bead in issue.get("beads", [])]
    listed = Counter(entry["disposition"] for entry in register.bead_dispositions)
    total = len(in_issues) + len(register.bead_dispositions)
    lines = [
        "## Bead coverage",
        "",
        f"{total} beads from the prototype's ledger, each referenced once: {len(in_issues)} in an issue's "
        f"`beads`, and {len(register.bead_dispositions)} in `bead_dispositions`.",
        "",
    ]
    return lines + _count_table("Bead disposition", listed, BEAD_DISPOSITIONS)


def _rules_section(register: Register) -> list[str]:
    lines = ["## Design rules", "", "The owner's standing rules. They apply everywhere.", ""]
    lines += ["| Id | Rule | Sources | benchhand-next |", "|---|---|---|---|"]
    for rule in register.design_rules:
        sources = "; ".join(rule["sources"])
        lines.append(
            f"| {rule['id']} | {_cell(rule['rule'])} | {sources} | {_cell(rule['benchhand_next'])} |"
        )
    conflicts = [rule for rule in register.design_rules if "conflict" in rule]
    lines += ["", "### Conflicts with benchhand-next", ""]
    if not conflicts:
        return [*lines, "None.", ""]
    lines += ["Both positions are recorded; the register picks no winner.", ""]
    for rule in conflicts:
        lines += [
            f"- **{rule['id']}.** Prototype: {_cell(rule['conflict']['prototype'])}",
            f"  benchhand-next: {_cell(rule['conflict']['benchhand_next'])}",
        ]
    return [*lines, ""]


def _decide_section(register: Register) -> list[str]:
    lines = ["## For the owner to decide", ""]
    decide = [issue for issue in register.issues if issue["disposition"] == "decide"]
    if not decide:
        return [*lines, "None.", ""]
    lines += ["| Id | Issue | Recommendation |", "|---|---|---|"]
    lines += [
        f"| {issue['id']} | {_cell(issue['title'])} | {_cell(issue['recommendation'])} |" for issue in decide
    ]
    return [*lines, ""]


def _recheck_section(register: Register) -> list[str]:
    lines = ["## Needs a recheck", ""]
    recheck = [issue for issue in register.issues if issue.get("needs_recheck")]
    if not recheck:
        return [*lines, "None.", ""]
    lines += [
        "Their source was not updated in the session that wrote the register, so check the entry against "
        "the current source before acting on it.",
        "",
    ]
    lines += [
        f"- {issue['id']}: {_cell(issue['title'])} ({'; '.join(issue['sources'])})" for issue in recheck
    ]
    return [*lines, ""]


def render_register(register: Register) -> str:
    issues = register.issues
    lines = ["# Migration issue register", "", GENERATED_NOTICE, ""]
    lines += [
        "Every issue found in the prototype, by the test project, by the prototype's lead sessions and by the "
        "agentcad product test, and every bead in the prototype's ledger, with how benchhand-next addresses it. "
        "All of them are addressed in the new build. Each entry cites its source by name only, because the test "
        "project, the product test's report and the ledger are private.",
        "",
        f"The register follows the prototype at `{register.data['reference_commit'][:7]}`. The ledger "
        f"snapshot is from {register.snapshot['date']}; `just issues-sync` reports what changed since, in the "
        "ledger and in the test project's tracked lead files: each logged tool issue, each numbered item of the "
        "owner's tool-issues brief, and the side briefs and gate reports. Every tool issue and brief item is "
        "cited by at least one entry.",
        "",
        "## Issues",
        "",
    ]
    lines += _count_table("Kind", Counter(issue["kind"] for issue in issues), KINDS)
    lines += _count_table("Disposition", Counter(issue["disposition"] for issue in issues), DISPOSITIONS)
    phases = Counter(_phase(issue) for issue in issues)
    lines += _count_table("Phase", phases, [*(f"Phase {n}" for n in range(8)), "no phase"])
    lines += ["### By area and disposition", "", *_area_table(register)]
    lines += _bead_section(register)
    lines += _rules_section(register)
    lines += _decide_section(register)
    lines += _recheck_section(register)
    return "\n".join(lines).rstrip("\n") + "\n"
