// Check the placeholder pages, and list them by phase on /planned/.
//
// A placeholder page sets `phase: N` in its front matter; MarkdownContent renders its "Planned"
// aside. This script fails the build when
// - a `phase` names no phase of docs/design-plan.md's "Steps (phased)" list;
// - a page with `phase` also states its status in its own prose (STATUS_WORDING), outside code.
// It then writes src/content/docs/planned.md, grouped by phase, and src/generated/plan-phases.json,
// which MarkdownContent reads for the aside (both gitignored).
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { planPhases, planStepsUrl } from "../design-plan-phases.mjs";

const docsDir = fileURLToPath(new URL("../src/content/docs", import.meta.url));
const OUTPUT = "planned.md";
const phasesJson = fileURLToPath(new URL("../src/generated/plan-phases.json", import.meta.url));

// Status wording that belongs in the aside only. The aside says what is planned and when.
const STATUS_WORDING = /\b(planned|coming soon|not yet|yet to|will be|to be written|todo|tbd|wip|work in progress|placeholder|outline|until then|phase \d+)\b/i;

function pages(dir) {
  return readdirSync(dir, { recursive: true })
    .map((file) => file.split(path.sep).join("/"))
    .filter((file) => /\.mdx?$/.test(file) && file !== OUTPUT);
}

function parse(file) {
  const text = readFileSync(path.join(docsDir, file), "utf8");
  const match = text.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!match) throw new Error(`${file} has no front matter`);
  const [, frontMatter, body] = match;
  const field = (name) => frontMatter.match(new RegExp(`^${name}:\\s*(.+)$`, "m"))?.[1].replace(/^"(.*)"$/, "$1");
  const phase = field("phase");
  return { file, title: field("title"), description: field("description") ?? "", phase: phase === undefined ? undefined : Number(phase), body };
}

// Prose only: drop fenced code, inline code, link targets and HTML comments.
function prose(markdown) {
  return markdown
    .replace(/^```[\s\S]*?^```/gm, "")
    .replace(/`[^`\n]*`/g, "")
    .replace(/\]\([^)]*\)/g, "]")
    .replace(/<!--[\s\S]*?-->/g, "");
}

function problems(page, phases) {
  const found = [];
  if (!phases.has(page.phase)) found.push(`phase ${page.phase} is not in docs/design-plan.md (phases ${[...phases.keys()].join(", ")})`);
  const lines = `${page.title}\n${page.description}\n${prose(page.body)}`.split("\n");
  for (const line of lines) {
    const wording = line.match(STATUS_WORDING);
    if (wording) found.push(`status wording "${wording[0]}" in: ${line.trim()}`);
  }
  return found.map((problem) => `${page.file}: ${problem}`);
}

const routeOf = (file) => `/${file.replace(/\.mdx?$/, "").replace(/(^|\/)index$/, "")}/`.replace(/\/+/g, "/");

function index(planned, phases) {
  const lines = [
    "---",
    "title: Planned pages",
    "description: The pages that are outlines, by the design-plan phase that writes them.",
    "---",
    "",
    `Generated by \`site/scripts/planned-pages.mjs\` from each page's \`phase\`. The phases are the [design plan's steps](${planStepsUrl}).`,
    "",
  ];
  for (const [phase, title] of phases) {
    const inPhase = planned.filter((page) => page.phase === phase);
    if (inPhase.length === 0) continue;
    lines.push(`## Phase ${phase}: ${title}`, "");
    for (const page of inPhase) lines.push(`- [${page.title}](${routeOf(page.file)})`);
    lines.push("");
  }
  return lines.join("\n");
}

function main() {
  const phases = planPhases();
  const planned = pages(docsDir)
    .map(parse)
    .filter((page) => page.phase !== undefined)
    .sort((a, b) => a.phase - b.phase || a.file.localeCompare(b.file));
  const found = planned.flatMap((page) => problems(page, phases));
  if (found.length) {
    console.error(found.join("\n"));
    process.exit(1);
  }
  writeFileSync(path.join(docsDir, OUTPUT), index(planned, phases));
  mkdirSync(path.dirname(phasesJson), { recursive: true });
  writeFileSync(phasesJson, `${JSON.stringify({ stepsUrl: planStepsUrl, phases: Object.fromEntries(phases) }, null, 2)}\n`);
  console.log(`checked ${planned.length} planned pages; listed them in ${OUTPUT}`);
}

main();
