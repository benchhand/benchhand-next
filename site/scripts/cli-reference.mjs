// Write the CLI reference page from the benchhand CLI itself: Typer's `utils docs` renders every
// command of `benchhand.cli` to Markdown, run through `uv run` in the workspace environment. The page
// is gitignored and has no edit link; change a command's help text in packages/benchhand/src/benchhand/cli.py.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { repoRoot, repoUrl } from "../site-url.mjs";

const CLI_MODULE = "benchhand.cli";
const CLI_SOURCE = "packages/benchhand/src/benchhand/cli.py";
const page = fileURLToPath(new URL("../src/content/docs/reference/cli.md", import.meta.url));

function typerDocs() {
  const dir = mkdtempSync(path.join(tmpdir(), "cli-reference-"));
  try {
    const out = path.join(dir, "cli.md");
    const args = ["run", "--locked", "typer", CLI_MODULE, "utils", "docs", "--name", "benchhand", "--output", out];
    execFileSync("uv", args, { cwd: repoRoot, stdio: ["ignore", "ignore", "inherit"] });
    return readFileSync(out, "utf8");
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

function main() {
  const markdown = typerDocs();
  // Typer opens with "# benchhand"; the front matter title replaces it.
  const body = markdown.replace(/^# .*\n+/, "");
  const commands = [...body.matchAll(/^#{2,} `benchhand /gm)].length;
  const frontMatter = [
    "---",
    "title: CLI",
    "description: Every benchhand command, with its arguments and options, generated from the CLI.",
    "editUrl: false",
    "---",
    "",
    `Generated by \`site/scripts/cli-reference.mjs\` from [\`${CLI_SOURCE}\`](${repoUrl}/blob/main/${CLI_SOURCE}) with Typer's \`utils docs\`. Do not edit.`,
    "",
  ];
  writeFileSync(page, `${frontMatter.join("\n")}\n${body}`);
  console.log(`rendered ${commands} commands of ${CLI_MODULE} to reference/cli.md`);
}

main();
